#!/usr/bin/env node
/**
 * Bundles migrations/*.sql into functions/api/_migrations.js.
 *
 * Cloudflare Workers have no filesystem at runtime, so the migration runner
 * cannot read the .sql files directly. Rather than make people maintain SQL
 * inside a JavaScript string — where it loses syntax highlighting and nobody
 * will ever review it properly — the .sql files stay the source of truth and
 * this generates the module from them.
 *
 * Runs in postinstall, which Cloudflare executes on every deploy, so the bundle
 * cannot drift from the files. It is committed anyway so a checkout without an
 * install still has a working endpoint.
 *
 * The checksum is what makes an edited-after-applied migration detectable. Line
 * endings are normalised first, or a Windows checkout and a Linux CI would
 * disagree about every file.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'migrations');
const out = path.join(root, 'functions', 'api', '_migrations.js');

if (!fs.existsSync(dir)) {
  console.log('  migrations/: none, skipping');
  process.exit(0);
}

const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const entries = files.map((file) => {
  // 0002_public_read_allowlist.sql → version 0002, name public_read_allowlist
  const m = file.match(/^(\d+)[_-](.+)\.sql$/);
  if (!m) throw new Error(`migrations/${file}: name it <version>_<name>.sql, e.g. 0003_add_widgets.sql`);
  const sql = fs.readFileSync(path.join(dir, file), 'utf8').replace(/\r\n/g, '\n');
  return {
    version: m[1],
    name: m[2],
    file,
    checksum: crypto.createHash('sha256').update(sql).digest('hex').slice(0, 16),
    sql,
  };
});

const dupes = entries.map((e) => e.version).filter((v, i, a) => a.indexOf(v) !== i);
if (dupes.length) throw new Error(`Duplicate migration version(s): ${[...new Set(dupes)].join(', ')}`);

const banner = `/**
 * GENERATED by scripts/build-migrations.js — do not edit.
 * Source of truth is migrations/*.sql. Run \`npm run build:migrations\` after
 * adding one (postinstall does it automatically on deploy).
 */
`;

fs.writeFileSync(out, banner + 'export const MIGRATIONS = ' + JSON.stringify(entries, null, 2) + ';\n');
console.log(`  migrations: bundled ${entries.length} (${entries.map((e) => e.version).join(', ')}) → functions/api/_migrations.js`);
